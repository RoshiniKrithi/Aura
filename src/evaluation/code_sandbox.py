"""Isolated Process Code Execution Sandbox for Aura EXP-005 Evaluation Suite.

Provides CodeExecutionSandbox, ExecutionResult, CodeCompiler, CodeExecutor,
SandboxManager, and TestCaseRunner for isolated subprocess execution with resource limits.
"""

import ast
from dataclasses import dataclass
import logging
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
from typing import Dict, List, Optional, Tuple, Union

logger = logging.getLogger(__name__)


@dataclass
class ExecutionResult:
    """Diagnostic outcome of sandboxed code execution.

    Attributes:
        passed: True if all unit test assertions passed without error.
        status: Status string ("PASSED", "FAILED", "TIMEOUT", "COMPILATION_ERROR", "RUNTIME_ERROR").
        output: Captured standard output string.
        error: Captured standard error string.
        execution_time: Runtime duration in seconds.
        memory_bytes: Memory usage overhead in bytes.
    """

    passed: bool
    status: str
    output: str = ""
    error: str = ""
    execution_time: float = 0.0
    memory_bytes: int = 0


class CodeCompiler:
    """Validates syntax and compiles code snippets."""

    @staticmethod
    def validate_python_syntax(code: str) -> Tuple[bool, Optional[str]]:
        """Parses code AST to check for Python syntax errors.

        Args:
            code: Source code string.

        Returns:
            Tuple of (is_valid, error_message).
        """
        try:
            ast.parse(code)
            return True, None
        except SyntaxError as e:
            return False, f"SyntaxError at line {e.lineno}: {e.msg}"


class SandboxManager:
    """Manages ephemeral workspace directories for isolated code execution."""

    @staticmethod
    def create_ephemeral_workspace() -> tempfile.TemporaryDirectory:
        """Creates a temporary working directory for executing code snippets."""
        return tempfile.TemporaryDirectory(prefix="aura_sandbox_")


class CodeExecutionSandbox:
    """Isolated subprocess sandbox executing model code against unit test assertions."""

    def __init__(
        self,
        timeout_seconds: float = 5.0,
        max_memory_mb: int = 512,
    ) -> None:
        """Initializes CodeExecutionSandbox.

        Args:
            timeout_seconds: Maximum allowed CPU execution time in seconds.
            max_memory_mb: Maximum allowed host RAM memory in megabytes.
        """
        self.timeout_seconds = timeout_seconds
        self.max_memory_mb = max_memory_mb

    def execute_code(
        self,
        code_snippet: str,
        test_assertions: str,
        entry_point: Optional[str] = None,
    ) -> ExecutionResult:
        """Executes code + assertions in an isolated subprocess worker context.

        Args:
            code_snippet: Python source code snippet generated by Aura.
            test_assertions: Unit test assertions string (e.g. assert f(1) == 2).
            entry_point: Optional function name to verify.

        Returns:
            ExecutionResult container object.
        """
        # 1. Validate Syntax
        is_valid, syntax_err = CodeCompiler.validate_python_syntax(code_snippet)
        if not is_valid:
            return ExecutionResult(
                passed=False,
                status="COMPILATION_ERROR",
                error=syntax_err or "Syntax Error",
            )

        # Combine code and test assertions
        full_script = f"{code_snippet}\n\n# --- UNIT TEST ASSERTIONS ---\n{test_assertions}\n"

        with SandboxManager.create_ephemeral_workspace() as tmp_dir:
            script_path = Path(tmp_dir) / "submission.py"
            with open(script_path, "w", encoding="utf-8") as f:
                f.write(full_script)

            start_time = time.time()
            try:
                # Isolated subprocess execution
                process = subprocess.Popen(
                    [sys.executable, str(script_path)],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    cwd=tmp_dir,
                    env={
                        "PYTHONPATH": sys.path[0],
                        "PATH": os.environ.get("PATH", ""),
                    },
                    text=True,
                )

                stdout, stderr = process.communicate(timeout=self.timeout_seconds)
                elapsed = time.time() - start_time

                if process.returncode == 0:
                    return ExecutionResult(
                        passed=True,
                        status="PASSED",
                        output=stdout.strip(),
                        error=stderr.strip(),
                        execution_time=elapsed,
                    )
                else:
                    return ExecutionResult(
                        passed=False,
                        status="FAILED",
                        output=stdout.strip(),
                        error=stderr.strip() or f"Process exited with code {process.returncode}",
                        execution_time=elapsed,
                    )

            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
                return ExecutionResult(
                    passed=False,
                    status="TIMEOUT",
                    error=f"Execution timed out after {self.timeout_seconds}s",
                    execution_time=self.timeout_seconds,
                )
            except Exception as e:
                return ExecutionResult(
                    passed=False,
                    status="RUNTIME_ERROR",
                    error=str(e),
                    execution_time=time.time() - start_time,
                )


class TestCaseRunner:
    """Runs test assertions against model code using CodeExecutionSandbox."""

    __test__ = False

    def __init__(self, sandbox: Optional[CodeExecutionSandbox] = None) -> None:
        """Initializes TestCaseRunner.

        Args:
            sandbox: CodeExecutionSandbox instance.
        """
        self.sandbox = sandbox or CodeExecutionSandbox()

    def run_tests(
        self, code_solution: str, test_cases: List[str]
    ) -> List[ExecutionResult]:
        """Runs multiple test case strings against a code solution.

        Args:
            code_solution: Python code snippet string.
            test_cases: List of unit test assertion strings.

        Returns:
            List of ExecutionResult objects for each test case.
        """
        results = []
        for test in test_cases:
            res = self.sandbox.execute_code(code_snippet=code_solution, test_assertions=test)
            results.append(res)
        return results
